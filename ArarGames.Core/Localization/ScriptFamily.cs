namespace ArarGames.Core.Localization;

/// <summary>
/// Specifies the script family used by a language.
/// </summary>
public enum ScriptFamily
{
    /// <summary>Latin script.</summary>
    Latin,
    /// <summary>Cyrillic script.</summary>
    Cyrillic,
    /// <summary>Arabic script.</summary>
    Arabic,
    /// <summary>Indic script family.</summary>
    Indic,
    /// <summary>Chinese, Japanese, or Korean script.</summary>
    CJK,
    /// <summary>Thai script.</summary>
    Thai,
    /// <summary>Georgian script.</summary>
    Georgian,
    /// <summary>Armenian script.</summary>
    Armenian
}
